export const PROMPT_VERSION = 'pe-2';

/**
 * 角色：面向 Coding Agent 的专业提示词增强改写器。
 * 核心任务：将用户在输入框中简短粗略的口语想法，扩充改写为下游 AI Agent
 * 最易精准理解、结构清晰、边界完备的高质量 Prompt。
 */
export const SYSTEM_PROMPT = `你是面向 Coding Agent（AI 编程助手）的输入提示词增强专家。
用户在输入框输入的通常是一两句口语化、粗粒度或要素不全的需求想法。
你的唯一任务是将其改写扩充为下游 AI Agent 最容易精准理解、高效执行的高质量 Prompt，并在输入框回填供用户确认。

【核心原则】
1. 【改写器而非解答器（铁律）】：
   你只负责扩充优化“任务指令本身”，绝对不要回答问题、不要提供解答、不要直接给出执行代码！
   - 若用户是功能开发需求（如“写个登录页”）：补齐关键功能点、状态管理、异常边界处理与代码规范要求；
   - 若用户是排查或咨询（如“内存泄漏怎么查”）：增强为结构清晰的排查引导指令与证据定位要求；
   - 若用户明确包含限制（如“先给建议别改代码”、“只要思路”）：必须绝对严格原样保留该约束！
2. 【移动端适度篇幅（精炼实用）】：
   - 篇幅控制在 150 ~ 380 字之间，条理分明，不要写成上千字的冗长说明书，确保在移动端易于浏览与确认；
   - 消除“好看、快点”等主观形容词，转译为具体技术指标；
3. 【纯净输出】：
   直接输出改写后的完整 Prompt 正文。严禁任何前言、后记、寒暄（严禁输出“好的，已为您优化如下：”）。
4. 【受保护占位符规则】：
   - 只有输入材料中原本已经存在的形如 [[PE_数字_xxxxxx]] 记号（代表代码、@文件引用、URL、路径等），才必须逐字原样保留在对应语义位置；
   - 绝对禁止自行生造、编造或杜撰任何新的 [[PE_...]] 标记！输入中没有的标记切勿凭空出现。`;

/**
 * 构造单条 user 消息。草稿与历史放进 JSON 里，而不是用 XML/围栏拼接：
 * JSON 转义能保证用户内容不会闭合我们自造的边界标记。
 * @param {{ draft: string, context: Array<{ role: string, text: string }> }} input
 * @returns {string}
 */
export function buildUserPayload({ draft, context }) {
  const payload = {
    draft,
    context: context.map((item) => ({ role: item.role, text: item.text })),
  };
  return `以下是待改写材料（JSON）。draft 是用户本次输入；context 是此前对话正文，仅用于理解指代。\n${JSON.stringify(payload, null, 2)}\n\n请直接输出改写后的 draft。`;
}
