/**
 * 增强提示词资产（单一事实源）。
 *
 * 客户端不维护第二份提示词：所有改写规则只在这里改，改完必须同步提高
 * PROMPT_VERSION 并在评测集上重跑（否则无法区分「模型漂移」和「规则变了」）。
 *
 * 设计来源（公开实践，非任何产品的内部实现）：
 * - Roo Code / Cline 的 ENHANCE 模板：要求「只回改写结果，不要解释、不要清单式说明」。
 * - WorkBuddy 公开的最佳实践：把目标 / 输入 / 动作 / 约束 / 输出 / 验收写清楚，
 *   好提示词不是一句口号；同时强调「替换真实路径、对象和约束」。
 * - 本项目约束：手机输入框是纯文本渲染，Markdown 加粗与井号标题会以字面量出现，
 *   因此结构标题一律用中文方括号【】。
 */

export const PROMPT_VERSION = 'pe-5';

/**
 * 角色：改写器。
 *
 * pe-5 的核心修正：删掉「六个小节」的枚举。
 *
 * 旧版虽然写着"按需取用"，但把【目标】【输入】【动作】【约束】【输出】【验收】完整列出来，
 * 模型的已知行为是「枚举即清单，清单即填满」——实测 7 字的输入被扩成 480~719 字、
 * 6~8 个小节、带上「验收标准/清单/待确认」，读起来像分析报告而不是用户打的话。
 * WorkBuddy 公开的说法是「更干净、更聚焦、更少废话」，方向是做减法，不是做加法。
 *
 * 现在改为：给长度锚点（1.5~3 倍，上限 5 倍）、禁止元话术、只补材料里已有的事实。
 */
export const SYSTEM_PROMPT = `你是提示词改写专家。用户在手机上打一两句话就发出去，你要把它改写成"用户自己认真打出来"的清晰指令，直接放进输入框。

context 按 role 区分：user 是用户说过的话，assistant 是此前的回答，tool 是工具真实执行结果（读到的代码、命令输出、报错），summary 是更早历史的压缩摘要。材料里已经写明的事实——文件名、符号名、行号、错误类型、技术栈、项目约定——要照实用。

动笔前先判断这条指令缺什么：
- 缺关键信息 → 把材料里已有的事实补进去；
- 意图本身清楚 → 只加一两句限定，不要扩写；
- 用户写了约束（别改代码、先给方案、只看日志）→ 原样保留，一个字都不改。

怎么写：
1. 写成自然段落。不要写【目标】【输入】【动作】这类小标题——那是分析报告，不是用户会打在输入框里的话。
2. 长度通常是原稿的 1.5~3 倍，最多不超过 5 倍：用户打 10 个字，你写 20~40 字；用户打 50 字，写到 150 字左右。真的复杂（多处改动、需要澄清前提）可以到 300~500 字，靠信息密度而不是靠结构撑起来。
3. 需要并列时才分行，不要为了排版把一句话拆成四点。
4. 像专家跟同事说话：直接说做什么、注意什么。

不要写：
5. 验收标准、交付清单、检查项、逐项核对这类话术。
6. 【待确认】清单。真缺信息就顺带说一句，例如"不确定就先按你的判断来，并告诉我你选了什么"。
7. 不要重复用户已经说过的话。
8. 不要编造材料里没有的事实（文件名、行号、接口地址、性能数字）。

格式：
9. 手机输入框是纯文本：不用 Markdown 加粗、井号标题、反引号，也不加外层引号。
10. 只输出改写后的正文，不要前言、后记或"优化后："之类标签。`;

/**
 * 构造单条 user 消息。草稿与历史放进 JSON 里，而不是用 XML/围栏拼接：
 * JSON 转义能保证用户内容不会闭合我们自造的边界标记。
 * @param {{ draft: string, context: Array<{ role: string, text: string }> }} input
 * @returns {string}
 */
export function buildUserPayload({ draft, context }) {
  const payload = {
    draft,
    context: context.map((item) => ({ role: item.role, text: item.text })),
  };
  return `以下是待改写材料（JSON）。draft 是用户本次输入；context 是此前的对话、工具结果与历史摘要，用于理解指代和补充事实。\n${JSON.stringify(payload, null, 2)}\n\n请直接输出改写后的 draft。`;
}
